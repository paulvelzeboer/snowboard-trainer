#!/usr/bin/env python3
"""Builds ../pistes.js: downhill pistes and lifts around the base (OpenStreetMap via Overpass)
with length, vertical drop and gradient per piste (elevation: EU-DEM 25 m via opentopodata.org).
Run by hand when the data should be refreshed:  python3 tools/build_pistes.py"""
import hashlib, json, math, os, sys, time, urllib.parse, urllib.request

BASE = (45.257285, 6.264863)      # Les Balcons des Aiguilles, La Toussuire
RADIUS = 4000                     # metres around the base
UA = {"User-Agent": "snowboard-trainer-map/1.0"}
HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, ".cache")

def get(url, data=None, name=None):
    path = os.path.join(CACHE, name) if name else None
    if path and os.path.exists(path):
        return json.load(open(path))
    req = urllib.request.Request(url, data=data, headers=UA)
    out = json.load(urllib.request.urlopen(req, timeout=90)); time.sleep(1.1)   # be polite to the free APIs
    if path:
        os.makedirs(CACHE, exist_ok=True); json.dump(out, open(path, "w"))
    return out

def dist(a, b):
    k = math.cos(math.radians(a[0]))
    return math.hypot((a[0]-b[0])*111320, (a[1]-b[1])*111320*k)

def resample(pts, step=40):
    """Points every ~step metres along a line, endpoints included."""
    out, carry = [pts[0]], 0.0
    for a, b in zip(pts, pts[1:]):
        d = dist(a, b)
        if d == 0: continue
        t = step - carry
        while t < d:
            f = t/d; out.append((a[0]+(b[0]-a[0])*f, a[1]+(b[1]-a[1])*f)); t += step
        carry = (carry + d) % step
    if out[-1] != pts[-1]: out.append(pts[-1])
    return out

def elevations(points):
    out = []
    for i in range(0, len(points), 100):
        chunk = points[i:i+100]
        loc = "|".join(f"{p[0]:.5f},{p[1]:.5f}" for p in chunk)
        r = get("https://api.opentopodata.org/v1/eudem25m?locations=" + urllib.parse.quote(loc, safe=",|"), name=f"elev_{hashlib.sha1(loc.encode()).hexdigest()[:16]}.json")
        out += [x["elevation"] for x in r["results"]]
    return out

q = f'[out:json][timeout:60];(way(around:{RADIUS},{BASE[0]},{BASE[1]})["piste:type"="downhill"];way(around:{RADIUS},{BASE[0]},{BASE[1]})[aerialway];);out tags geom;'
els = get("https://overpass-api.de/api/interpreter", urllib.parse.urlencode({"data": q}).encode(), "overpass.json")["elements"]

DIFF = {"novice": "green", "easy": "blue", "intermediate": "red", "advanced": "black", "expert": "black"}
LIFTS = {"chair_lift", "gondola", "drag_lift", "platter", "t-bar", "magic_carpet", "cable_car", "mixed_lift", "j-bar", "rope_tow"}
pistes, lifts = {}, []
for e in els:
    t = e.get("tags", {}); g = [(p["lat"], p["lon"]) for p in e.get("geometry", [])]
    if len(g) < 2: continue
    if t.get("aerialway") in LIFTS:
        lifts.append({"n": t.get("name", ""), "k": t["aerialway"], "g": g})
    elif t.get("piste:type") == "downhill" and t.get("area") != "yes" and g[0] != g[-1]:
        c = DIFF.get(t.get("piste:difficulty"))
        if not c: continue
        key = (t.get("name") or f"?{e['id']}", c)
        pistes.setdefault(key, []).append(g)

out_p = []
for (name, col), segs in sorted(pistes.items()):
    samples = [resample(s) for s in segs]
    flat = [p for s in samples for p in s]
    ele = elevations(flat) if not name.startswith("?") else None
    rec = {"n": "" if name.startswith("?") else name, "c": col, "g": segs, "len": round(sum(dist(a, b) for s in segs for a, b in zip(s, s[1:])))}
    if ele and all(x is not None for x in ele):
        rec["top"], rec["bot"] = round(max(ele)), round(min(ele))
        rec["avg"] = round(100*(max(ele)-min(ele))/max(rec["len"], 1))
        # steepest ~120 m stretch within one segment
        steep, i = 0, 0
        for s in samples:
            e = ele[i:i+len(s)]; i += len(s)
            for a in range(len(s)-3):
                steep = max(steep, abs(e[a]-e[a+3])/120*100)
        rec["max"] = round(steep)
    out_p.append(rec)

r5 = lambda g: [[round(a, 5), round(b, 5)] for a, b in g]
for p in out_p: p["g"] = [r5(s) for s in p["g"]]
for l in lifts: l["g"] = r5(l["g"])
js = "// Generated by tools/build_pistes.py from OpenStreetMap (ODbL) and EU-DEM elevation data. Do not edit by hand.\nconst PISTES=" + json.dumps(out_p, ensure_ascii=False, separators=(",", ":")) + ";\nconst LIFTS=" + json.dumps(lifts, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(HERE, "..", "pistes.js"), "w").write(js)
named = [p for p in out_p if p["n"]]
print(len(out_p), "pistes,", len(named), "named,", len(lifts), "lifts,", len(js)//1024, "KB", file=sys.stderr)
for p in sorted(named, key=lambda p: (p["c"], p.get("avg", 0))):
    print(f'{p["c"]:6} {p["n"][:28]:28} {p["len"]:5} m  {p.get("top","?")}->{p.get("bot","?")}  avg {p.get("avg","?")}%  max {p.get("max","?")}%')
